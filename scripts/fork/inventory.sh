#!/usr/bin/env bash
# Run from any directory with bash scripts/fork/inventory.sh.
# External commands are limited to grep, sort and awk; traversal includes hidden files.
set -euo pipefail
export LC_ALL=C
cd -- "${BASH_SOURCE[0]%/*}/../.."

excludes=(
  --exclude-dir=.git --exclude-dir=node_modules --exclude-dir=target
  --exclude=Cargo.lock --exclude=pnpm-lock.yaml
  --exclude=FORK-INVENTORY.md --exclude=inventory.sh
)

# grep status 1 means an empty category, not an error. Other failures abort the report.
scan() {
  local pattern=$1 status
  shift
  if grep -rIHniE "${excludes[@]}" -e "$pattern" "$@"; then
    :
  else
    status=$?
    [[ $status == 1 ]] || return "$status"
  fi
}

# Input is path:line:text, sorted by path. Count matching lines, not word occurrences.
# Legal-looking lines are listed separately and must survive any later rename.
summarize() {
  local title=$1 action=$2 note=$3
  sort -u | awk -F: -v title="$title" -v action="$action" -v note="$note" '
    {
      path = $1
      sub(/^\.\//, "", path)
      if (!(path in seen)) { seen[path] = 1; paths[++files] = path }
      text = $0
      sub(/^[^:]*:[0-9]+:/, "", text)
      legal = path ~ /(^|\/)(LICENSE[^\/]*|COPYING[^\/]*|NOTICE[^\/]*|THIRD-PARTY-NOTICES\.md)$/ ||
        tolower(text) ~ /copyright|spdx|attribution|licensed?([[:space:]]|["=:])|fork of|based on|derived from|original author/
      if (legal) { keep[path]++; kept++ } else { hits[path]++; ordinary++ }
      total++
    }
    END {
      printf "## %s — %s\n\n%s\n\n", title, action, note
      printf "Count: %d matching lines in %d files.\n\n", total, files
      printf "%s: %d matching lines. KEEP (legal attribution): %d matching lines.\n\n", action, ordinary, kept
      if (!total) { print "No matches (0).\n"; exit }
      print "| File | Matching lines | Disposition |"
      print "| --- | ---: | --- |"
      for (i = 1; i <= files; i++) {
        path = paths[i]
        if (hits[path]) printf "| `%s` | %d | %s |\n", path, hits[path], action
        if (keep[path]) printf "| `%s` | %d | KEEP (legal attribution) |\n", path, keep[path]
      }
      print ""
    }
  '
}

network_candidates() {
  # Include indirect/dynamic call sites as well as literal non-music hosts. This is a
  # review list: dependencies, fixtures, comments and privacy denials are not proof of telemetry.
  scan 'telemetry|analytics|crash.?report|crashlytics|sentry|bugsnag|posthog|segment\.com|amplitude|mixpanel|remote.?config|fetch[[:space:](]|reqwest|URLSession|https?://|wss?://' . |
    awk -F: '
      {
        text = tolower($0)
        sub(/^[^:]*:[0-9]+:/, "", text)
        if (text ~ /telemetry|analytics|crash.?report|crashlytics|sentry|bugsnag|posthog|segment\.com|amplitude|mixpanel|remote.?config|fetch[[:space:](]|reqwest|urlsession/) {
          print; next
        }
        # Strip known music/media URLs; retain any other literal URL on the same line.
        gsub(/https?:\/\/([a-z0-9-]+\.)*(youtube\.com|youtu\.be|youtube-nocookie\.com|googlevideo\.com|ytimg\.com|ggpht\.com|spotify\.com|scdn\.co|apple\.com|itunes\.com|mzstatic\.com|deezer\.com|dzcdn\.net|tidal\.com|qobuz\.com|soundcloud\.com|sndcdn\.com|bandcamp\.com|last\.fm|audioscrobbler\.com|lrclib\.net|musixmatch\.com|genius\.com|lrc\.lib|librivox\.org|archive\.org|sponsor\.ajay\.app)([:\/][^[:space:]"<>]*)?/, "", text)
        if (text ~ /https?:\/\/|wss?:\/\//) print
      }
    '
}

# Bash glob traversal also lists empty binary assets, without inspecting their contents.
asset_paths() {
  local path
  for path in "$1"/*; do
    [[ -e $path || -L $path ]] || continue
    case ${path##*/} in
      .git|node_modules|target|Cargo.lock|pnpm-lock.yaml|FORK-INVENTORY.md|inventory.sh) continue ;;
    esac
    if [[ -d $path && ! -L $path ]]; then
      asset_paths "$path"
    elif [[ -f $path ]]; then
      printf '%s\n' "$path"
    fi
  done
}

{
  printf '# Fork identity inventory\n\n'
  printf 'Generated by `bash scripts/fork/inventory.sh`; reflects the current working tree.\n\n'
  printf 'Scope: recursive text search, including hidden files, excluding `.git`, `node_modules`, `target`, `Cargo.lock`, `pnpm-lock.yaml`, this generator and this report. Binary content is skipped; category 9 lists image asset paths only.\n\n'
  printf 'Counts are matching source lines per file (a line can match multiple categories), except category 9 counts paths. Case-insensitive identity searches include lowercase names. No timestamps or machine-specific absolute paths are emitted.\n\n'
  printf 'REPLACE means a future fork-specific replacement, not authorization to rename now. KEEP (legal attribution) preserves legal files and attribution-looking lines; this heuristic does not decide legal obligations. VERIFY requires human review of compatibility, purpose or rights. Comments, fixtures, secret-variable names and inactive settings are included; a match does not prove an active hook or a configured credential.\n\n'

  scan 'chladni' . | summarize '0. Current fork identity: Chladni' VERIFY 'T2 sets the display name, desktop/iOS identifiers and URL scheme. Includes provenance and documentation, not just active app settings.'
  scan 'spotless' . | summarize '1. Legacy product name: Spotless' REPLACE 'T2 retains migration sources, compatibility keys/protocols, attribution, artwork and out-of-scope historical files. Review purpose before replacing; see docs/FORK-NOTICE.md.'
  scan 'encore|limusic' . | summarize '2. Internal names: Encore and limusic' VERIFY 'Review crate/module names, paths referenced in text, storage keys and deep links before changing compatibility-sensitive names.'
  scan 'fjenn|opena\.tech|github\.com/fjenn' . | summarize '3. Author/handle and upstream hosts' VERIFY 'Separate upstream ownership and service dependencies from acknowledgements that must remain.'
  scan 'app\.spotless[a-z0-9_.-]*' . | summarize '4. Legacy bundle/app identifiers: app.spotless*' VERIFY 'T2 uses studio.chladni.desktop and studio.chladni.ios. Legacy import strings, history and untouched release workflows may still match; signing and migration require separate verification.'
  scan 'team[ _-]?id|development[ _-]?team|sign([ _-]?(identity|identities))|code[ _-]?sign|signing|provision|notari|notary|keychain[ _-]?profile|developer id|apple_(certificate|cert|api)' scripts .github/workflows ios src-tauri |
    summarize '5. Apple teams, signing and provisioning/notarization' VERIFY 'Includes script/workflow inputs, placeholders and iOS project/export settings. Counts do not imply actual credentials or populated team IDs.'
  scan 'updater|latest\.json|pubkey|public[ _-]?key|endpoints|releases/(latest|download)|TAURI_SIGNING' src-tauri/tauri*.conf.json ui/src/lib/updater* .github/workflows |
    summarize '6. Updater endpoints and public keys' REPLACE 'Includes disabled/empty config and workflow artifact publishing. The fork updater must stay disabled until its own endpoint and key pair are configured.'
  scan 'https?://|mailto:' . |
    awk 'tolower($0) ~ /website|support|privacy|bug|issues|discussions|donat|sponsor|funding|ko-fi|kofi|patreon|paypal|buymeacoffee|opena\.tech|github\.com\/fjenn/' |
    summarize '7. Website/support/privacy/bug-report/donation URLs' VERIFY 'Review destinations and ownership before using any as fork-facing links. Third-party service links and legal links may need to remain.'
  network_candidates |
    summarize '8. Telemetry/analytics/crash/remote-config and network review' VERIFY 'Includes fetch/reqwest/URLSession call sites, hook keywords and non-music URL literals, even when hosts are stored separately. Review dynamic targets and false positives. In particular inspect crates/core/src/sync/relay.rs (opena.tech sync relay) and crates/core/src/cipher/config.rs (remote cipher registries); these are not classified as telemetry merely because they are remote.'

  printf '## 9. Icons, logos and screenshots — VERIFY\n\n'
  printf 'All image/icon asset paths, conservatively including artwork and fixtures. No asset content is read into this report; inspect rights and identity visually before replacement.\n\n'
  shopt -s nullglob dotglob
  asset_paths . | awk 'tolower($0) ~ /\.(png|svg|ico|icns|jpe?g|webp|gif|avif|bmp|tiff?|heic|pdf)$/ { sub(/^\.\//, ""); print }' |
    sort -u | awk '
      { paths[++count] = $0 }
      END {
        printf "Count: %d asset paths.\n\n", count
        if (!count) { print "No matches (0)."; exit }
        for (i = 1; i <= count; i++) printf "- `%s`\n", paths[i]
      }
    '
} > docs/FORK-INVENTORY.md
